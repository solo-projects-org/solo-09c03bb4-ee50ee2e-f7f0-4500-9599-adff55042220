"""Build the two sample GTFS packages checked into ``samples/``.

Run from the repository root:

    python tools/make_samples.py

The generator is deterministic so the checked-in ZIPs can be regenerated byte
for byte (ZIP timestamps are fixed).
"""

from __future__ import annotations

import io
import zipfile
from pathlib import Path

OUT_DIR = Path(__file__).resolve().parent.parent / "samples"
FIXED_DATE = (2026, 1, 1, 0, 0, 0)

# ---------------------------------------------------------------------------
# Version 1
# ---------------------------------------------------------------------------

V1_STOPS = [
    ("S1", "中央车站"),
    ("S2", "人民广场"),
    ("S3", "科技馆"),
    ("S4", "火车站"),
    ("S5", "机场"),
    ("S6", "大学城"),
]

V1_TRIPS = [
    ("T1", "R1"),
    ("T2", "R1"),
    ("T3", "R2"),
]

# (trip_id, stop_id, stop_sequence, arrival_time)
V1_STOP_TIMES = [
    ("T1", "S1", "1", "06:00:00"),
    ("T1", "S2", "2", "06:12:00"),
    ("T1", "S3", "3", "06:25:00"),
    ("T2", "S1", "1", "23:40:00"),
    ("T2", "S2", "2", "23:52:00"),
    ("T2", "S3", "3", "24:05:00"),   # past midnight service day
    ("T2", "S4", "4", "24:18:00"),
    ("T3", "S5", "10", "07:00:00"),
    ("T3", "S6", "20", "07:20:00"),
    ("T3", "S3", "30", "07:45:00"),
]

# ---------------------------------------------------------------------------
# Version 2 — same trips, changed times / added stops and a new trip.
# ---------------------------------------------------------------------------

V2_STOPS = V1_STOPS + [("S7", "滨江公园"), ("S8", "新城区")]

V2_TRIPS = [
    ("T1", "R1"),
    ("T2", "R1"),
    ("T3", "R2"),
    ("T4", "R3"),
]

V2_STOP_TIMES = [
    # T1 now runs express: skips S2 and arrives earlier.
    ("T1", "S1", "1", "06:00:00"),
    ("T1", "S3", "2", "06:18:00"),
    ("T2", "S1", "1", "23:40:00"),
    ("T2", "S2", "2", "23:52:00"),
    ("T2", "S3", "3", "24:05:00"),
    ("T2", "S4", "4", "24:18:00"),
    ("T2", "S7", "5", "24:30:00"),
    # T3 keeps its old route but gets later times.
    ("T3", "S5", "10", "07:10:00"),
    ("T3", "S6", "20", "07:30:00"),
    ("T3", "S3", "30", "07:55:00"),
    # New late-night trip crossing well past midnight.
    ("T4", "S1", "1", "22:00:00"),
    ("T4", "S2", "2", "22:15:00"),
    ("T4", "S4", "3", "22:40:00"),
    ("T4", "S8", "4", "25:10:00"),
]


def _csv(header: list[str], rows: list[tuple]) -> str:
    import csv

    buffer = io.StringIO()
    writer = csv.writer(buffer, lineterminator="\n")
    writer.writerow(header)
    writer.writerows(rows)
    return buffer.getvalue()


def _build(stops, trips, stop_times) -> bytes:
    files = {
        "stops.txt": _csv(["stop_id", "stop_name"], stops),
        "trips.txt": _csv(["route_id", "service_id", "trip_id"], [
            (route_id, "WEEKDAY", trip_id) for trip_id, route_id in trips
        ]),
        "stop_times.txt": _csv(
            ["trip_id", "arrival_time", "departure_time", "stop_id", "stop_sequence"],
            [
                (trip_id, arrival, arrival, stop_id, sequence)
                for trip_id, stop_id, sequence, arrival in stop_times
            ],
        ),
        "agency.txt": "agency_id,agency_name,agency_url,agency_timezone\n"
                      "A1,市公交公司,https://example.org,Asia/Shanghai\n",
    }
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w", compression=zipfile.ZIP_DEFLATED) as zf:
        for name, text in files.items():
            info = zipfile.ZipInfo(name, date_time=FIXED_DATE)
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o644 << 16
            zf.writestr(info, text)
    return buffer.getvalue()


def main() -> None:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    (OUT_DIR / "gtfs_v1.zip").write_bytes(_build(V1_STOPS, V1_TRIPS, V1_STOP_TIMES))
    (OUT_DIR / "gtfs_v2.zip").write_bytes(_build(V2_STOPS, V2_TRIPS, V2_STOP_TIMES))
    print(f"wrote {OUT_DIR/'gtfs_v1.zip'} and {OUT_DIR/'gtfs_v2.zip'}")


if __name__ == "__main__":
    main()
